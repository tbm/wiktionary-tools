LANGCODE_TEMPLATES_IGNORE = (
    # Specifically used to refer to other languages
    "lang",
    # Often used to highlight questions about other languages in etymologies
    "attention",
)


def fix_lang_code(text, lang):
    """
    Fix the language code in templates that require it.
    """
    code = mwparserfromhell.parse(text)

    for template in code.filter_templates(recursive=True):
        template_name = str(template.name).strip()
        if template_name not in LANGCODE_TEMPLATES:
            continue
        if template_name in LANGCODE_TEMPLATES_IGNORE:
            continue
        # affix with nocat is no problem
        if template.has("nocat"):
            continue
        # quote templates can put the actual language code in termlang
        if template.has("termlang"):
            continue
        # By default, the language code is parameter 1 but this is
        # not always the case.
        param = "1"
        if not template.has(param):
            continue
        val = str(template.get(param).value)
        # quote templates allow a comma-separated list of language codes.
        # Let's ignore those to avoid adding too much complexity.
        if template_name.startswith("quote-") or template_name.startswith("cite-"):
            if "," in val:
                continue
        # "surf" allows + syntax in parameter 1, pushing the lang code
        # to parameter 2
        if template_name.startswith("surf") and val.lstrip().startswith("+"):
            # +lit has no lang code
            if val.strip() == "+lit":
                continue
            param = "2"
            val = str(template.get(param).value)
        old_langcode = get_langcode(val)
        if not old_langcode:
            continue
        if not lang_codes_match(old_langcode, lang, permissive=True):
            template.get(param).value = val.replace(old_langcode, lang, count=1)
    return str(code)
